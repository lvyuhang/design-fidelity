#!/usr/bin/env python3
"""Machine-checkable fidelity rules for React/TSX/CSS page code.

The web counterpart of dart_fidelity_lint.py. Each rule names the verified
alternative from @design-fidelity/react. A line may opt out only with a reason,
`// fidelity-lint: allow W005 <reason>` (or `/* ... */` in CSS), on the same or
the previous line. Generated `.g.tsx` files are trusted only while their bytes
match the codegen report.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
from pathlib import Path

from dart_fidelity_lint import ARROW_OR_SYMBOL

EXTENSIONS = ('.tsx', '.ts', '.jsx', '.js', '.mjs', '.css', '.scss', '.less')
CODE_RULES = {
    'W001': ('icon_library', r'''from\s+['"](?:react-icons|@mui/icons-material|lucide-react|@heroicons/|@fortawesome/|@ant-design/icons|@tabler/icons)''',
             'Icon library instead of the source asset. Use SourceAsset, a SourceBox path shape or SourcePlaceholder.'),
    'W004': ('raw_text_style', r'\b(?:fontSize|lineHeight|fontFamily|letterSpacing|fontWeight)\s*:|(?<![\w-])(?:font-size|line-height|font-family|letter-spacing|font-weight)\s*:',
             'Hand-written text metrics. Use SourceText with <Page>Tokens text specs (or sourceTextStyle).'),
    'W005': ('raw_shadow', r'\b(?:boxShadow|textShadow)\s*:|(?<![\w-])(?:box-shadow|text-shadow)\s*:|drop-shadow\s*\(',
             'Use SourceShadow in SourceBox (one blur mapping, knocked out under the shape).'),
    'W006': ('raw_blur', r'\bbackdropFilter\s*:|(?<![\w-])backdrop-filter\s*:|\bblur\s*\(',
             'Use SourceBackdropBlur / SourceLayerBlur (calibrated radius mapping).'),
    'W007': ('raw_border', r'\bborder(?:Top|Right|Bottom|Left)?(?:Width|Color|Style)?\s*:|(?<![\w-])border(?:-(?:top|right|bottom|left))?(?:-(?:width|color|style))?\s*:|\boutline\s*:',
             'Border position must be explicit. Use SourceBorder (inside / center / outside).'),
    'W009': ('no_text_scaling', r'text-size-adjust\s*:\s*none|textSizeAdjust\s*:\s*[\'"]none|user-scalable\s*=\s*no|maximum-scale\s*=\s*1(?:\.0)?\b',
             'Production text must keep the browser font-size setting and zoom.'),
    'W010': ('raw_image', r'<img\b|\bbackground(?:Image)?\s*:\s*[\'"`]?url\(|(?<![\w-])background(?:-image)?\s*:\s*url\(',
             'Use SourceAsset with the prepared export frame.'),
}
COLOR_IN_STRING = re.compile(r'#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?)\s*\(')
COLOR_IN_CSS = re.compile(r':\s*[^;{}]*?(#[0-9a-fA-F]{3,8}\b|\b(?:rgba?|hsla?)\s*\()')
MESSAGES = {
    'W002': 'Arrow/emoji glyph used as an icon. Use the source asset or a complete source path; '
            'missing assets use SourcePlaceholder.',
    'W003': 'Colour literal in page code. Use the generated <Page>Tokens colours.',
}
SUPPRESS = re.compile(r'fidelity-lint:\s*allow\s+(W\d{3})\b\s*(.*?)\s*(?:\*/)?\s*$')
GENERATED_HEADER = '// GENERATED by design-fidelity/scripts/'


def scan(text: str, css: bool = False):
    """Code with strings/comments blanked, plus strings and comments."""
    code, strings, comments = [], [], []
    i, n = 0, len(text)
    while i < n:
        if not css and text.startswith('//', i):
            end = text.find('\n', i)
            end = n if end < 0 else end
            comments.append((i, text[i:end]))
            code.append(' ' * (end - i))
            i = end
            continue
        if text.startswith('/*', i):
            end = text.find('*/', i + 2)
            end = n if end < 0 else end + 2
            comments.append((i, text[i:end]))
            code.append(re.sub(r'[^\n]', ' ', text[i:end]))
            i = end
            continue
        ch = text[i]
        if ch in ('"', "'", '`'):
            j = i + 1
            while j < n and text[j] != ch:
                if text[j] == '\\':
                    j += 2
                    continue
                if ch == '`' and text.startswith('${', j):
                    depth, j = 1, j + 2
                    while j < n and depth:
                        depth += {'{': 1, '}': -1}.get(text[j], 0)
                        j += 1
                    continue
                if ch != '`' and text[j] == '\n':
                    break
                j += 1
            strings.append((i, text[i + 1:j]))
            code.append(ch + re.sub(r'[^\n]', ' ', text[i + 1:j]) + (ch if j < n else ''))
            i = min(n, j + 1)
            continue
        code.append(ch)
        i += 1
    return ''.join(code), strings, comments


def _line(text: str, offset: int) -> int:
    return text.count('\n', 0, offset) + 1


def lint_text(text: str, rel: str):
    css = rel.endswith(('.css', '.scss', '.less'))
    code, strings, comments = scan(text, css)
    allowed: dict[int, dict[str, str]] = {}
    for offset, body in comments:
        match = SUPPRESS.search(body)
        if match:
            line = _line(text, offset)
            for target in (line, line + 1):
                allowed.setdefault(target, {})[match.group(1)] = match.group(2).strip()
    findings, suppressed = [], []

    def report(rule: str, offset: int, symbol: str) -> None:
        line = _line(text, offset)
        reason = allowed.get(line, {}).get(rule)
        name = CODE_RULES[rule][0] if rule in CODE_RULES else {'W002': 'glyph_icon', 'W003': 'color_literal'}[rule]
        entry = {'rule': rule, 'name': name, 'file': rel, 'line': line, 'symbol': symbol}
        if reason is not None:
            if reason:
                suppressed.append({**entry, 'reason': reason})
                return
            entry['message'] = 'Suppression needs a reason after the rule id.'
        else:
            entry['message'] = CODE_RULES[rule][2] if rule in CODE_RULES else MESSAGES[rule]
        findings.append(entry)

    # Property names live in code; import paths and url()/viewport values in strings.
    for rule, (_, pattern, _) in CODE_RULES.items():
        source = text if rule in ('W001', 'W009', 'W010') else code
        for match in re.finditer(pattern, source):
            if source is text and _in(match.start(), comments):
                continue
            report(rule, match.start(), match.group(0).strip())
    if css:
        for match in COLOR_IN_CSS.finditer(code):
            report('W003', match.start(1), match.group(1))
    for offset, value in strings:
        if not css and COLOR_IN_STRING.search(value) and not value.startswith(('data:', 'http')):
            report('W003', offset, value[:40])
        if value and ARROW_OR_SYMBOL.match(value):
            report('W002', offset, value)
    for match in re.finditer(r'>\s*([^<>{}\n]+?)\s*<', code):
        if ARROW_OR_SYMBOL.match(match.group(1)):
            report('W002', match.start(1), match.group(1))
    return findings, suppressed


def _in(offset: int, spans) -> bool:
    return any(start <= offset < start + len(body) for start, body in spans)


def report_path_for(path: Path) -> Path:
    name = path.name
    for suffix in ('.g.tsx', '.g.ts', '.tsx', '.ts'):
        if name.endswith(suffix):
            return path.with_name(name[:-len(suffix)] + '.codegen.json')
    return path.with_suffix('.codegen.json')


def check_generated(path: Path, rel: str):
    text = path.read_text(errors='replace')
    if not text.startswith(GENERATED_HEADER):
        return None
    report = report_path_for(path)
    if not report.exists():
        return {'rule': 'W011', 'name': 'generated_without_report', 'file': rel, 'line': 1,
                'message': f'Missing {report.name}; regenerate instead of editing by hand.'}
    expected = json.loads(report.read_text()).get('output_sha256')
    if expected != hashlib.sha256(path.read_bytes()).hexdigest():
        return {'rule': 'W011', 'name': 'generated_file_edited', 'file': rel, 'line': 1,
                'message': 'Generated file differs from its codegen report. Do not hand-edit; '
                           'use overrides/onTap in page code or regenerate.'}
    return {'ok': True}


def lint(paths, root: Path):
    findings, suppressed, checked, generated = [], [], [], []
    for path in paths:
        try:
            rel = str(path.resolve().relative_to(root.resolve()))
        except ValueError:
            rel = str(path.resolve())
        wrapped = f'/{rel}'
        if '/design-fidelity-react/' in wrapped or '/support/' in wrapped or '/node_modules/' in wrapped \
                or re.search(r'\.(test|spec)\.[jt]sx?$', path.name):
            continue  # Primitives, harness and tests may use raw CSS.
        checked.append(rel)
        integrity = check_generated(path, rel)
        if integrity is not None:
            generated.append(rel)
            if not integrity.get('ok'):
                findings.append(integrity)
            continue
        found, allowed = lint_text(path.read_text(errors='replace'), rel)
        findings.extend(found)
        suppressed.extend(allowed)
    return {'status': 'PASS' if not findings else 'FAIL', 'findings': findings,
            'suppressed': suppressed, 'checked_files': checked, 'generated_files': generated}


def web_inputs(contract: dict, base: Path):
    return [(base / p).resolve() for p in contract.get('implementation_inputs', [])
            if str(p).endswith(EXTENSIONS)]


def lint_contract(contract_path: Path):
    contract = json.loads(contract_path.read_text())
    if contract.get('web_lint') in (None, 'off'):
        return {'status': 'SKIPPED', 'reason': contract.get('web_lint_reason', 'web_lint not enabled'),
                'findings': [], 'suppressed': []}
    base = contract_path.resolve().parent
    paths = web_inputs(contract, base)
    root = Path(os.path.commonpath([str(base), *(str(p) for p in paths)])) if paths else base
    return lint(paths, root)


def expand(sources):
    files = []
    for source in sources:
        if source.is_dir():
            files.extend(sorted(p for p in source.rglob('*') if p.suffix in EXTENSIONS
                                and 'node_modules' not in p.parts))
        else:
            files.append(source)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--contract', type=Path)
    parser.add_argument('paths', type=Path, nargs='*')
    parser.add_argument('--root', type=Path, default=Path.cwd())
    args = parser.parse_args()
    result = lint_contract(args.contract) if args.contract else lint(expand(args.paths), args.root)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 1 if result['status'] == 'FAIL' else 0


if __name__ == '__main__':
    raise SystemExit(main())

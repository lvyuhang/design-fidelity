#!/usr/bin/env python3
"""Fidelity rules for Jetpack Compose (Kotlin, Kxxx) and SwiftUI (Swift, Sxxx) page code.

The native counterparts of dart_fidelity_lint.py / web_fidelity_lint.py: each
rule names the verified primitive to use instead. Opt out on the same or the
previous line with `// fidelity-lint: allow K005 <reason>`. Generated
`.g.kt` / `.g.swift` files are trusted only while they match their codegen report.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
from pathlib import Path

from web_fidelity_lint import scan

KOTLIN = {
    'K001': ('framework_icon', r'\bIcons\.(?:Default|Filled|Outlined|Rounded|Sharp|TwoTone|AutoMirrored)\.',
             'Material icon instead of the source asset. Use SourceAsset, a SourceBox path or SourcePlaceholder.'),
    'K003': ('color_literal', r'\bColor\s*\(\s*(?:0x|red\s*=)|\bColor\.(?:Red|Blue|Green|Black|White|Gray|LightGray|DarkGray|Yellow|Cyan|Magenta)\b',
             'Colour literal in page code. Use the generated <Page>Tokens colours.'),
    'K004': ('raw_text_style', r'(?<![\w.])TextStyle\s*\(|\bfontSize\s*=|\blineHeight\s*=',
             'Hand-built text style. Use SourceText with <Page>Tokens text specs.'),
    'K005': ('raw_shadow', r'\.shadow\s*\(|\belevation\s*=|\bshadowElevation\s*=',
             'Compose shadows tint translucent fills and use another blur kernel. Use SourceShadow in SourceBox.'),
    'K006': ('raw_blur', r'\.blur\s*\(|\bRenderEffect\b|\bBlurMaskFilter\b',
             'Use SourceLayerBlur (one calibrated radius mapping).'),
    'K007': ('raw_border', r'\.border\s*\(|\bBorderStroke\s*\(',
             'Border position must be explicit. Use SourceBorder (Inside / Center / Outside).'),
    'K008': ('icon_button', r'\bIconButton\s*\(',
             'IconButton adds a minimum touch size and padding. Use SourceNode + onTap.'),
    'K009': ('no_text_scaling', r'\bfontScale\s*=\s*1(?:\.0)?f?\b',
             'Production text must keep the system font scale; only the fidelity harness pins it.'),
    'K010': ('raw_image', r'\bpainterResource\s*\(|\bAsyncImage\s*\(|(?<![\w.])Image\s*\(\s*painter',
             'Use SourceAsset with the prepared export frame.'),
    'K013': ('raw_text', r'(?<![\w.])(?:Text|BasicText)\s*\(',
             'Use SourceText so line height, leading and font padding are fixed.'),
}
SWIFT = {
    'S001': ('framework_icon', r'\bImage\s*\(\s*systemName\s*:',
             'SF Symbol instead of the source asset. Use SourceAsset, a SourceBox path or SourcePlaceholder.'),
    'S003': ('color_literal', r'\bColor\s*\(\s*(?:red\s*:|\.sRGB|#colorLiteral|hex\s*:)|\bColor\.(?:red|blue|green|black|white|gray|yellow|orange|pink|purple)\b|\bUIColor\s*\(',
             'Colour literal in page code. Use the generated <Page>Tokens colours.'),
    'S004': ('raw_font', r'\.font\s*\(|\bFont\.(?:system|custom)\s*\(|\.lineSpacing\s*\(',
             'Hand-built font metrics. Use SourceText with <Page>Tokens text specs.'),
    'S005': ('raw_shadow', r'\.shadow\s*\(',
             'SwiftUI shadows are not knocked out and use another kernel. Use SourceShadow in SourceBox.'),
    'S006': ('raw_blur', r'\.blur\s*\(|\.(?:ultraThin|thin|regular|thick|ultraThick)Material\b',
             'Use SourceLayerBlur; materials have no calibrated radius.'),
    'S007': ('raw_border', r'\.border\s*\(|\.strokeBorder\s*\(|\.stroke\s*\(',
             'Border position must be explicit. Use SourceBorder (inside / center / outside).'),
    'S009': ('no_text_scaling', r'\.dynamicTypeSize\s*\(\s*\.(?:large|medium|small)\s*\)',
             'Production text must keep Dynamic Type; only the fidelity harness pins it.'),
    'S010': ('raw_image', r'(?<![\w.])Image\s*\(\s*(?:"|uiImage\s*:)|\bAsyncImage\s*\(',
             'Use SourceAsset with the prepared export frame.'),
    'S013': ('raw_text', r'(?<![\w.])Text\s*\(',
             'Use SourceText so line height and tracking follow the source.'),
}
RULES = {'.kt': KOTLIN, '.kts': KOTLIN, '.swift': SWIFT}
SUPPRESS = re.compile(r'fidelity-lint:\s*allow\s+([KS]\d{3})\b\s*(.*)')
GENERATED_HEADER = '// GENERATED by design-fidelity/scripts/'


def _line(text: str, offset: int) -> int:
    return text.count('\n', 0, offset) + 1


def lint_text(text: str, rel: str):
    rules = RULES[Path(rel).suffix]
    code, strings, comments = scan(text)
    allowed: dict[int, dict[str, str]] = {}
    for offset, body in comments:
        match = SUPPRESS.search(body)
        if match:
            line = _line(text, offset)
            for target in (line, line + 1):
                allowed.setdefault(target, {})[match.group(1)] = match.group(2).strip()
    findings, suppressed = [], []
    for rule, (name, pattern, message) in rules.items():
        for match in re.finditer(pattern, code):
            line = _line(text, match.start())
            entry = {'rule': rule, 'name': name, 'file': rel, 'line': line, 'symbol': match.group(0).strip()}
            reason = allowed.get(line, {}).get(rule)
            if reason:
                suppressed.append({**entry, 'reason': reason})
            else:
                findings.append({**entry, 'message': message if reason is None
                                 else 'Suppression needs a reason after the rule id.'})
    return findings, suppressed


def report_path_for(path: Path) -> Path:
    for suffix in ('.g.kt', '.g.swift'):
        if path.name.endswith(suffix):
            return path.with_name(path.name[:-len(suffix)] + '.codegen.json')
    return path.with_suffix('.codegen.json')


def check_generated(path: Path, rel: str, prefix: str):
    text = path.read_text(errors='replace')
    if not text.startswith(GENERATED_HEADER):
        return None
    report = report_path_for(path)
    if not report.exists():
        return {'rule': f'{prefix}011', 'name': 'generated_without_report', 'file': rel, 'line': 1,
                'message': f'Missing {report.name}; regenerate instead of editing by hand.'}
    expected = json.loads(report.read_text()).get('output_sha256')
    if expected != hashlib.sha256(path.read_bytes()).hexdigest():
        return {'rule': f'{prefix}011', 'name': 'generated_file_edited', 'file': rel, 'line': 1,
                'message': 'Generated file differs from its codegen report. Do not hand-edit; '
                           'use overrides/onTap in page code or regenerate.'}
    return {'ok': True}


def lint(paths, root: Path):
    findings, suppressed, checked, generated = [], [], [], []
    for path in paths:
        if path.suffix not in RULES:
            continue
        try:
            rel = str(path.resolve().relative_to(root.resolve()))
        except ValueError:
            rel = str(path.resolve())
        wrapped = f'/{rel}'
        if '/design/fidelity/' in wrapped or '/DesignFidelity/' in wrapped or '/support/' in wrapped.lower() \
                or re.search(r'Tests?\.(kt|swift)$', path.name):
            continue  # primitives, harness and tests may use raw APIs
        checked.append(rel)
        integrity = check_generated(path, rel, 'K' if path.suffix != '.swift' else 'S')
        if integrity is not None:
            generated.append(rel)
            if not integrity.get('ok'):
                findings.append(integrity)
            continue
        found, allowed = lint_text(path.read_text(errors='replace'), rel)
        findings.extend(found)
        suppressed.extend(allowed)
    return {'status': 'PASS' if not findings else 'FAIL', 'findings': findings,
            'suppressed': suppressed, 'checked_files': checked, 'generated_files': generated}


def lint_contract(contract_path: Path):
    contract = json.loads(contract_path.read_text())
    key = {'compose': 'kotlin_lint', 'swiftui': 'swift_lint'}.get(contract.get('target'))
    if key is None or contract.get(key) in (None, 'off'):
        return {'status': 'SKIPPED', 'reason': contract.get(f'{key}_reason', 'native lint not enabled'),
                'findings': [], 'suppressed': []}
    base = contract_path.resolve().parent
    paths = [(base / p).resolve() for p in contract.get('implementation_inputs', [])
             if Path(p).suffix in RULES]
    root = Path(os.path.commonpath([str(base), *(str(p) for p in paths)])) if paths else base
    return lint(paths, root)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--contract', type=Path)
    parser.add_argument('paths', type=Path, nargs='*')
    parser.add_argument('--root', type=Path, default=Path.cwd())
    args = parser.parse_args()
    if args.contract:
        result = lint_contract(args.contract)
    else:
        files = [p for s in args.paths for p in (sorted(s.rglob('*')) if s.is_dir() else [s])]
        result = lint(files, args.root)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    return 1 if result['status'] == 'FAIL' else 0


if __name__ == '__main__':
    raise SystemExit(main())

"""Compose and SwiftUI targets (preview): same scene model, Kotlin / Swift output.

Syntax is checked when FIDELITY_KOTLIN_SYNTAX / FIDELITY_SWIFT_SYNTAX name a
checker that takes file paths (e.g. tree-sitter based); compiling and pixel
tests need the Android / Xcode toolchains on a developer machine.
"""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE.parent / 'scripts'
ASSETS = HERE.parent / 'assets'
sys.path[:0] = [str(SCRIPTS), str(HERE)]
from generate import generate  # noqa: E402
from native_fidelity_lint import lint, lint_text  # noqa: E402
import test_emit_react  # noqa: E402


def syntax_errors(variable, paths):
    checker = os.environ.get(variable)
    if not checker:
        return None
    run = subprocess.run([checker, *map(str, paths)], capture_output=True, text=True)
    return '' if run.returncode == 0 else run.stdout + run.stderr


class NativeEmitterTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        base = test_emit_react.EmitReactTests('test_scene_uses_primitives_tokens_and_node_ids')
        base.setUp()
        self.addCleanup(base.doCleanups)
        self.source, self.plan = base.root / 'source.json', base.root / 'plan.json'
        self.app = self.root / 'app'

    def compose(self):
        output = self.app / 'app/src/main/kotlin/com/example/shop/fidelity/Fixture.g.kt'
        test = self.app / 'app/src/test/kotlin/fidelity/FixtureFidelityTest.kt'
        report = generate([self.source], self.plan, None, 'Fixture', output, app_root=self.app,
                          asset_dir='app/src/main/assets/design/fixture', render_test=test,
                          output_env='PAGE_RENDER_OUTPUT', target='compose')
        return report, output.read_text(), test

    def swiftui(self):
        output = self.app / 'Shop/Fidelity/Fixture.g.swift'
        test = self.app / 'ShopTests/Fidelity/FixtureFidelityTests.swift'
        report = generate([self.source], self.plan, None, 'Fixture', output, app_root=self.app,
                          asset_dir='Shop/DesignAssets/fixture', render_test=test,
                          output_env='PAGE_RENDER_OUTPUT', target='swiftui', options={'module': 'Shop'})
        return report, output.read_text(), test

    def test_compose_scene(self):
        report, kt, test = self.compose()
        self.assertTrue(kt.startswith('// GENERATED by design-fidelity/scripts/generate.py --target compose'))
        self.assertIn('package com.example.shop.fidelity', kt)
        self.assertIn('fun FixtureScene(', kt)
        self.assertIn('Box(Modifier.sourcePlaced(left = 16f, right = 16f, top = insets.dy + 100f, height = 146f))', kt)
        self.assertIn('SourceNode("CARD")', kt)
        self.assertIn('SourceBorder(thickness = 1f, fill = SourceFill.Solid(FixtureTokens.cFFEEDCC4), '
                      'position = SourceBorderPosition.Inside)', kt)
        self.assertIn('SourceNode("LABEL", fill = false)', kt)
        self.assertIn('const val icon = "design/fixture/icon.png"', kt)
        self.assertIn('SourceAsset(FixtureAssets.icon, exportRect = SourceRect(-1f, -1f, 24f, 24f))', kt)
        self.assertIn('bottom = 0f, height = insets.dyBottom + 50f', kt)  # tab bar bleeds into the home indicator
        self.assertIn('SourceClip(SourceRectShape(12f))', kt)
        features = {u['feature'] for u in report['unsupported']}
        self.assertIn('backdrop_blur', features)
        self.assertTrue((self.app / 'app/src/main/assets/design/fixture/icon.png').is_file())
        harness = (test.parent / 'support' / 'FidelityHarness.kt').read_text()
        self.assertIn('package fidelity.support', harness)
        self.assertIn('qualifiers = "w430dp-h932dp-xhdpi"', test.read_text())  # render_scale 2
        scene = json.loads((test.parent / 'Fixture.scene.g.json').read_text())
        self.assertIn('stroke', {c['kind'] for c in scene['checks']})
        statuses = {o['kind']: o['status'] for o in report['scene_test']['obligations']}
        self.assertEqual(statuses['backdrop'], 'unsupported')
        self.assertTrue(Path(report['scene_test']['runner']).is_file())
        errors = syntax_errors('FIDELITY_KOTLIN_SYNTAX', [self.app / 'app/src/main/kotlin/com/example/shop/fidelity/Fixture.g.kt',
                                                          test, test.parent / 'support/FidelityHarness.kt',
                                                          Path(report['scene_test']['runner'])])
        if errors is not None:
            self.assertEqual(errors, '', errors)

    def test_compose_harness_package_follows_test_directory(self):
        output = self.app / 'app/src/main/kotlin/com/example/shop/Fixture.g.kt'
        test = self.app / 'app/src/test/kotlin/com/example/shop/FixtureFidelityTest.kt'
        generate([self.source], self.plan, None, 'Fixture', output, app_root=self.app, render_test=test,
                 target='compose')
        self.assertIn('package com.example.shop.support', (test.parent / 'support/FidelityHarness.kt').read_text())
        self.assertIn('import com.example.shop.support.FidelityHarness', test.read_text())

    def test_swiftui_scene(self):
        report, swift, test = self.swiftui()
        self.assertTrue(swift.startswith('// GENERATED by design-fidelity/scripts/generate.py --target swiftui'))
        self.assertIn('public struct FixtureScene: View {', swift)
        self.assertIn('SourcePlaced(left: 16, top: insets.dy + 100, right: 16, height: 146) {', swift)
        self.assertIn('SourceBorder(thickness: 1, fill: .solid(FixtureTokens.cFFEEDCC4), position: .inside)', swift)
        self.assertIn('public static let icon = "fixture/icon.png"', swift)
        self.assertIn('SourceClip(.rect(12)) {', swift)
        self.assertIn('Color(.sRGB, red: 238 / 255.0, green: 220 / 255.0, blue: 196 / 255.0, opacity: 255 / 255.0)', swift)
        self.assertIn('@testable import Shop', test.read_text())
        self.assertTrue((test.parent / 'Support' / 'FidelityHarness.swift').is_file())
        # ViewBuilder closures are chunked to at most ten children.
        depth_children = swift.count('Group {')
        self.assertGreaterEqual(depth_children, 1)
        errors = syntax_errors('FIDELITY_SWIFT_SYNTAX', [self.app / 'Shop/Fidelity/Fixture.g.swift', test,
                                                         test.parent / 'Support/FidelityHarness.swift',
                                                         Path(report['scene_test']['runner'])])
        if errors is not None:
            self.assertEqual(errors, '', errors)

    def test_generated_native_code_passes_lint_and_edits_are_caught(self):
        _, kt, _ = self.compose()
        _, swift, _ = self.swiftui()
        files = [self.app / 'app/src/main/kotlin/com/example/shop/fidelity/Fixture.g.kt',
                 self.app / 'Shop/Fidelity/Fixture.g.swift']
        result = lint(files, self.app)
        self.assertEqual(result['status'], 'PASS', result['findings'])
        files[1].write_text(swift.replace('opacity: 255 / 255.0', 'opacity: 1', 1))
        self.assertEqual(lint(files, self.app)['findings'][0]['rule'], 'S011')

    def test_lint_rules(self):
        rules = lambda text, name: [f['rule'] for f in lint_text(text, name)[0]]  # noqa: E731
        self.assertEqual(rules('val a = Color(0xFF00FF00)\nModifier.shadow(4.dp)\nText("x")', 'a.kt'),
                         ['K003', 'K005', 'K013'])
        self.assertEqual(rules('Image(systemName: "x")\nText("y").font(.system(size: 12))', 'a.swift'),
                         ['S001', 'S004', 'S013'])
        found, allowed = lint_text('// fidelity-lint: allow K007 product border\nval b = Modifier.border(1.dp, c)', 'a.kt')
        self.assertEqual((found, allowed[0]['reason']), ([], 'product border'))


class NativePrimitiveSourceTests(unittest.TestCase):
    """The packaged primitives parse (full compile happens on developer machines)."""

    def test_package_sources_parse(self):
        kotlin = sorted((ASSETS / 'compose').rglob('*.kt'))
        swift = sorted((ASSETS / 'swiftui').rglob('*.swift'))
        self.assertGreaterEqual(len(kotlin), 6)
        self.assertGreaterEqual(len(swift), 6)
        for variable, files in (('FIDELITY_KOTLIN_SYNTAX', kotlin), ('FIDELITY_SWIFT_SYNTAX', swift)):
            errors = syntax_errors(variable, files)
            if errors is not None:
                self.assertEqual(errors, '', errors)


if __name__ == '__main__':
    unittest.main()

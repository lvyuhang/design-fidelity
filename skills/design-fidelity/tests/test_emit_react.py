class EmitReactTests(unittest.TestCase):
    def setUp(self):
        temp = tempfile.TemporaryDirectory()
        self.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        (self.root / 'source.json').write_text(json.dumps(fixture(), ensure_ascii=False))
        from PIL import Image
        Image.new('RGBA', (96, 96), (0, 120, 255, 255)).save(self.root / 'icon.png')
        plan = {'snapshot_id': 'snap', 'resolved_version': 'ver', 'render_scale': 2,
                'assets': [{'asset_id': 'ICON:image', 'node_id': 'ICON', 'kind': 'exported_asset',
                            'path': str(self.root / 'icon.png'),
                            'export_rect': [34, 260, 24, 24], 'layout_rect': [35, 261, 22, 22]}],
                'fonts': [{'source_family': 'PingFangSC-Regular', 'weight': 400, 'runtime_family': 'SourcePingFang'},
                          {'source_family': 'PingFangSC-Semibold', 'weight': 600, 'runtime_family': 'SourcePingFang'}]}
        (self.root / 'plan.json').write_text(json.dumps(plan))
        self.app = self.root / 'app'
        self.output = self.app / 'src/fidelity/fixture.g.tsx'
        self.render = self.app / 'fidelity/fixture/render.tsx'
        self.report = generate([self.root / 'source.json'], self.root / 'plan.json', None, 'Fixture',
                               self.output, app_root=self.app, asset_dir='src/assets/design/fixture',
                               render_test=self.render, output_env='PAGE_RENDER_OUTPUT', target='react')
        self.tsx = self.output.read_text()
        self.by_id = {n['node_id']: n for n in self.report['nodes']}

    def test_scene_uses_primitives_tokens_and_node_ids(self):
        self.assertTrue(self.tsx.startswith('// GENERATED by design-fidelity/scripts/generate.py --target react'))
        self.assertIn("from '@design-fidelity/react';", self.tsx)
        self.assertIn('export function FixtureScene(', self.tsx)
        self.assertIn('<SourceNode id="CARD" fill>', self.tsx)
        self.assertIn("borders={[{ thickness: 1, fill: { color: FixtureTokens.cFFEEDCC4 }, position: \"inside\" }]}", self.tsx)
        self.assertIn('shadows={[{ color: FixtureTokens.c14D89B47, offset: [0, 1], blur: 10 }]}', self.tsx)
        self.assertIn("cFFEEDCC4: '#EEDCC4FF'", self.tsx)
        self.assertIn('<SourceBackdropBlur radius={20}', self.tsx)
        self.assertIn('<SourceClip shape={{ kind: "rect", radii: 12 }}>', self.tsx)
        self.assertIn('<SourcePlaceholder nodeId="IMG" />', self.tsx)
        self.assertIn('import iconAsset from "../assets/design/fixture/icon.png";', self.tsx)
        self.assertIn('exportRect={[-1, -1, 24, 24]}', self.tsx)
        self.assertTrue((self.app / 'src/assets/design/fixture/icon.png').is_file())
        # Text keeps its intrinsic box; status bar / home indicator are not painted.
        self.assertIn('<SourceNode id="LABEL">', self.tsx)
        for chrome in ('"TIME"', '"BAR"', '"WIFI"'):
            self.assertNotIn(chrome, self.tsx)
        self.assertIn('FixtureScene.designPadding = { top: 44, bottom: 34 } as const;', self.tsx)

    def test_safe_area_footer_and_root_offsets(self):
        self.assertIn('bottom={dyBottom(', self.tsx)
        self.assertIn('top={dy(100)}', self.tsx)
        footer = self.report['layout']['footer']
        self.assertIn('TABBAR', footer)
        self.assertIn('footer={', self.tsx)

    def test_text_layer_fill_colours_glyphs(self):
        self.assertIn('cFFA7A199', self.tsx)
        note = [line for line in self.tsx.splitlines() if '"说明文字"' in line][0]
        self.assertIn('cFFA7A199', next(l for l in self.tsx.splitlines()
                                        if l.strip().startswith('get ') and 'cFFA7A199' in l))
        self.assertIn('style={FixtureTokens.t12w400h17cFFA7A199}', note)

    def test_unkeyed_nodes_are_not_geometry_checked(self):
        decisions = self.report['draft_node_decisions']
        self.assertIs(decisions['ART'].get('geometry'), False)
        self.assertNotIn('geometry', decisions['CARD'])
        self.assertNotIn('geometry', decisions['LABEL'])

    def test_report_records_target_and_web_approximations(self):
        self.assertEqual(self.report['target'], 'react')
        self.assertEqual(self.by_id['CARD']['primitive'], 'SourceBox')
        features = {u['feature'] for u in self.report['unsupported']}
        self.assertIn('rotation', features)
        self.assertTrue(self.report['assets'][0]['app_asset'].startswith('src/assets/design/fixture/'))
        self.assertTrue((self.app / 'src/fidelity/fixture.codegen.json').is_file())

    def test_render_entry_harness_and_scene_spec(self):
        entry = self.render.read_text()
        self.assertIn("from '../../src/fidelity/fixture.g';", entry)
        self.assertIn('scale: 2,', entry)
        harness = self.render.parent / 'support' / 'fidelity_render_harness.cjs'
        self.assertEqual(harness.read_bytes(), (ASSETS / 'web' / 'fidelity_render_harness.cjs').read_bytes())
        spec = json.loads((self.render.parent / 'scene.g.json').read_text())
        self.assertEqual(spec['scene'], 'FixtureScene')
        kinds = {c['kind'] for c in spec['checks']}
        self.assertTrue({'stroke', 'backdrop', 'clip'} <= kinds, kinds)
        obligations = self.report['scene_test']['obligations']
        self.assertTrue(all(o['status'] == 'bound' for o in obligations if o['kind'] in ('stroke', 'backdrop')))

    def test_generated_code_passes_web_lint(self):
        result = lint([self.output, self.render], self.app)
        self.assertEqual(result['status'], 'PASS', result['findings'])
        self.assertEqual(result['generated_files'], ['src/fidelity/fixture.g.tsx'])
        self.output.write_text(self.tsx.replace('radius={20}', 'radius={18}'))
        self.assertEqual(lint([self.output], self.app)['findings'][0]['rule'], 'W011')

    @unittest.skipUnless(node_has('esbuild', 'react'), 'esbuild/react not installed')
    def test_tsx_bundles(self):
        script = ("require('esbuild').build({entryPoints:[process.argv[1]],bundle:true,write:false,"
                  "jsx:'automatic',loader:{'.png':'file'},outdir:'/tmp',alias:{'@design-fidelity/react':process.argv[2]},"
                  "nodePaths:(process.env.NODE_PATH||'').split(':').filter(Boolean),logLevel:'error'})"
                  ".then(()=>console.log('ok')).catch(e=>{console.error(e.message);process.exit(1)})")
        run = subprocess.run(['node', '-e', script, str(self.render), str(PACKAGE)], env=node_env(),
                             capture_output=True, text=True)
        self.assertEqual(run.returncode, 0, run.stderr)

    @unittest.skipUnless(node_has('esbuild', 'react', 'react-dom', 'playwright'), 'web toolchain not installed')
    def test_chromium_render_geometry_and_scene_checks(self):
        out = self.root / 'out' / 'render.png'
        env = dict(node_env(), PAGE_RENDER_OUTPUT=str(out))
        harness = str(self.render.parent / 'support' / 'fidelity_render_harness.cjs')
        run = subprocess.run(['node', harness, str(self.render)], cwd=self.app, env=env,
                             capture_output=True, text=True, timeout=180)
        self.assertEqual(run.returncode, 0, run.stderr[-3000:])
        from PIL import Image
        with Image.open(out) as im:
            self.assertEqual(im.size, (750, 1624))
        geometry = json.loads(out.with_name('render.png.geometry.json').read_text())
        self.assertEqual(geometry['schema'], 1)
        for key, rect in {'CARD': [16, 100, 343, 146], 'BUTTON': [28, 706, 320, 50], 'DOT': [32, 515, 5, 5]}.items():
            for actual, expected in zip(geometry['nodes'][key], rect):
                self.assertAlmostEqual(actual, expected, delta=0.01, msg=key)
        self.assertIn('LABEL', geometry['text_nodes'])
        variants = json.loads(out.with_name('render.png.variants.json').read_text())['variants']
        self.assertEqual(len(variants), 10)
        se = next(v for v in variants if v['device'] == 'iphone_se' and v['text_scale'] == 1)
        self.assertTrue(se['scrollable'])
        self.assertAlmostEqual(se['nodes']['CARD'][1], 100 - 44 + 20, delta=0.01)
        # The tab bar is drawn under the home indicator in the design: it keeps
        # that 0 distance to the screen bottom on a taller device.
        tab = next(v for v in variants if v['device'] == 'iphone_15' and v['text_scale'] == 1)['nodes']['TABBAR']
        self.assertAlmostEqual(tab[1] + tab[3], 852, delta=0.01)
        scene = subprocess.run(['node', harness, str(self.render), '--scene', str(self.render.parent / 'scene.g.json')],
                               cwd=self.app, env=env, capture_output=True, text=True, timeout=180)
        self.assertEqual(scene.returncode, 0, scene.stdout[-3000:] + scene.stderr[-2000:])
        self.assertEqual(json.loads(scene.stdout)['status'], 'PASS')


class WebLintTests(unittest.TestCase):
    def rules(self, text, name='page.tsx'):
        return [f['rule'] for f in lint_text(text, name)[0]]

    def test_rules_name_the_primitive_alternative(self):
        self.assertEqual(self.rules("import { X } from 'lucide-react';"), ['W001'])
        self.assertEqual(self.rules("const s = { boxShadow: '0 1px 2px x' };"), ['W005'])
        self.assertEqual(self.rules("const s = { color: '#ff0000' };"), ['W003'])
        self.assertEqual(self.rules("const s = { fontSize: 14 };"), ['W004'])
        self.assertEqual(self.rules("const s = { border: 0 };"), ['W007'])
        self.assertEqual(self.rules('const a = <img src={u} />;'), ['W010'])
        self.assertEqual(self.rules('const a = <span>›</span>;'), ['W002'])
        self.assertEqual(self.rules('.a { box-shadow: none; color: #fff }', 'a.css'), ['W005', 'W003'])

    def test_comments_and_suppressions(self):
        self.assertEqual(self.rules('// color: #fff\n/* boxShadow: x */'), [])
        findings, suppressed = lint_text('// fidelity-lint: allow W005 product elevation\n'
                                         "const s = { boxShadow: 'x' };", 'p.tsx')
        self.assertEqual(findings, [])
        self.assertEqual(suppressed[0]['reason'], 'product elevation')
        findings, _ = lint_text("// fidelity-lint: allow W005\nconst s = { boxShadow: 'x' };", 'p.tsx')
        self.assertIn('needs a reason', findings[0]['message'])



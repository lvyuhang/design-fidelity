def node_env():
    env = dict(os.environ)
    # FIDELITY_NODE_PATH points at a node_modules with react, react-dom, esbuild, playwright.
    extra = os.environ.get('FIDELITY_NODE_PATH') or ('/opt/npm-tools/node_modules'
                                                     if Path('/opt/npm-tools/node_modules').is_dir() else '')
    if extra:
        env['NODE_PATH'] = os.pathsep.join(p for p in (extra, env.get('NODE_PATH', '')) if p)
    env['DESIGN_FIDELITY_REACT'] = str(PACKAGE)
    return env


def node_has(*modules):
    if not shutil.which('node'):
        return False
    script = ';'.join(f"require.resolve({json.dumps(m)})" for m in modules)
    return subprocess.run(['node', '-e', script], env=node_env(), capture_output=True).returncode == 0



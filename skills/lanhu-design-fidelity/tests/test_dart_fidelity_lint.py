"""Prose prohibitions as executable rules: each rule has a violating and a clean case."""
import hashlib
import json
from pathlib import Path
import sys
import tempfile
import unittest

SCRIPTS = Path(__file__).resolve().parents[1] / 'scripts'
sys.path.insert(0, str(SCRIPTS))
from dart_fidelity_lint import lint, lint_contract, lint_text, scan  # noqa: E402

VIOLATIONS = {
    'L001': "Icon(Icons.chevron_right)",
    'L002': "SourceText('›', style: T.a)",
    'L003': "const ColoredBox(color: Color(0xFFFFFFFF))",
    'L004': "Text('x', style: TextStyle(fontSize: 12))",
    'L005': "BoxDecoration(boxShadow: [BoxShadow(blurRadius: 4)])",
    'L006': "BackdropFilter(filter: ImageFilter.blur(sigmaX: 4))",
    'L007': "BoxDecoration(border: Border.all(width: 1))",
    'L008': "IconButton(onPressed: f, icon: back)",
    'L009': "FittedBox(child: name)",
    'L010': "MediaQuery(data: d.copyWith(textScaler: TextScaler.noScaling))",
    'L012': "Image.asset('assets/a.png')",
    'L013': "Text('昵称')",
}
CLEAN = """
import 'package:lanhu_fidelity/lanhu_fidelity.dart';
// Icons.close and Color(0xFF000000) in comments are fine.
/* BoxShadow( in a block comment */
Widget build() => SourceBox(
  fills: const [SourceFill.color(PageTokens.cFFFFFFFF)],
  child: SourceText('Icons.add 不是图标', style: PageTokens.t14),
);
final label = 'TextStyle( inside a string';
final transparent = Colors.transparent;
final greeting = 'Hi ${user['name']} >';
"""


class DartFidelityLintTests(unittest.TestCase):
    def rules(self, source):
        findings, _ = lint_text(source, 'page.dart')
        return {f['rule'] for f in findings}

    def test_each_rule_fires_on_its_violation(self):
        for rule, source in VIOLATIONS.items():
            with self.subTest(rule=rule):
                self.assertIn(rule, self.rules(source))

    def test_primitives_comments_and_strings_are_clean(self):
        self.assertEqual(self.rules(CLEAN), set())

    def test_suppression_needs_a_reason_and_is_disclosed(self):
        source = "// lanhu-lint: allow L009 marquee banner is designed to scale\nFittedBox(child: a)\n"
        findings, suppressed = lint_text(source, 'page.dart')
        self.assertEqual(findings, [])
        self.assertEqual(suppressed[0]['reason'], 'marquee banner is designed to scale')
        findings, _ = lint_text("FittedBox(child: a) // lanhu-lint: allow L009\n", 'page.dart')
        self.assertEqual(findings[0]['message'], 'Suppression needs a reason after the rule id.')
        findings, _ = lint_text("// lanhu-lint: allow L003 wrong rule\nFittedBox(child: a)\n", 'p.dart')
        self.assertEqual({f['rule'] for f in findings}, {'L009'})

    def test_scanner_keeps_offsets_and_interpolation(self):
        code, strings, comments = scan("a('x${b['y']}z') // c\n")
        self.assertEqual(len(code), len("a('x${b['y']}z') // c\n"))
        self.assertEqual([s for _, s in strings], ["x${b['y']}z"])
        self.assertEqual(len(comments), 1)

    def test_generated_files_must_match_their_report(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            generated = root / 'page.g.dart'
            body = ('// GENERATED by lanhu-design-fidelity/scripts/generate_flutter.py; do not edit.\n'
                    'const c = Color(0xFF000000);\n')
            generated.write_text(body)
            (root / 'page.codegen.json').write_text(json.dumps(
                {'output_sha256': hashlib.sha256(body.encode()).hexdigest()}))
            self.assertEqual(lint([generated], root)['status'], 'PASS')
            generated.write_text(body + 'final edited = 1;\n')
            result = lint([generated], root)
            self.assertEqual(result['findings'][0]['rule'], 'L011')

    def test_contract_profile(self):
        with tempfile.TemporaryDirectory() as temp:
            root = Path(temp)
            (root / 'lib').mkdir()
            (root / 'lib/page.dart').write_text(VIOLATIONS['L001'])
            (root / 'test').mkdir()
            (root / 'test/page_test.dart').write_text(VIOLATIONS['L003'])
            contract = {'implementation_inputs': ['lib/page.dart', 'test/page_test.dart']}
            (root / 'c.json').write_text(json.dumps(contract))
            self.assertEqual(lint_contract(root / 'c.json')['status'], 'SKIPPED')
            contract['dart_lint'] = 'v1'
            (root / 'c.json').write_text(json.dumps(contract))
            result = lint_contract(root / 'c.json')
            self.assertEqual(result['status'], 'FAIL')
            self.assertEqual(result['checked_files'], ['lib/page.dart'], 'tests may use raw APIs')


if __name__ == '__main__':
    unittest.main()

#!/usr/bin/env python3
"""Machine-checkable replacements for prose prohibitions in page Dart code.

Each rule names the verified alternative. A line may opt out only with an
explicit reason, `// lanhu-lint: allow L005 <reason>`, on the same or the
previous line; every suppression is reported. Generated `.g.dart` files are
trusted only while their bytes match the codegen report (no hand edits).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
from pathlib import Path

RULES = {
    'L001': ('framework_icon', r'\b(?:Icons|CupertinoIcons)\.[A-Za-z_]\w*',
             'Framework icon instead of the source asset. Use SourceAsset, a complete '
             'SourcePathShape, or SourcePlaceholder.'),
    'L003': ('color_literal', r'\bColor\s*\(\s*0x|\bColor\.from(?:ARGB|RGBO)\s*\(|\bColors\.(?!transparent\b)[a-z]\w*',
             'Colour literal in page code. Use the generated <Page>Tokens constants.'),
    'L004': ('raw_text_style', r'(?<![\w.])TextStyle\s*\(',
             'Hand-built TextStyle inherits/omits metrics. Use <Page>Tokens text styles or '
             'sourceTextStyle(...).'),
    'L005': ('raw_shadow', r'\bBoxShadow\s*\(|(?<![\w.])Shadow\s*\(|\bPhysicalModel\s*\(|\belevation\s*:',
             'Flutter shadows tint translucent fills and use another blur kernel. Use SourceShadow '
             'in SourceBox.'),
    'L006': ('raw_blur', r'\bImageFilter\.blur\s*\(|\bBackdropFilter\s*\(|\bMaskFilter\.blur\s*\(',
             'Use SourceBackdropBlur / SourceLayerBlur (one calibrated radius mapping).'),
    'L007': ('raw_border', r'\bBorder\.all\s*\(|(?<![\w.])Border\s*\(|\bBorderSide\s*\(|\bstrokeAlign\s*:',
             'Border position must be explicit. Use SourceBorder(position: inside/center/outside).'),
    'L008': ('icon_button', r'\bIconButton\s*\(',
             'IconButton injects padding and minimum size from the theme. Use GestureDetector/'
             'InkWell around the source widget, keeping the tap target separate.'),
    'L009': ('fitted_box', r'\bFittedBox\s*\(',
             'FittedBox shrinks content to hide overflow and changes typography. Fix the layout '
             'or document the exception.'),
    'L010': ('no_text_scaling', r'\bTextScaler\.noScaling\b|\btextScaleFactor\s*:',
             'Production text must keep accessibility scaling; only the fidelity harness pins it.'),
    'L012': ('raw_image_asset', r'\bImage\.asset\s*\(|\bAssetImage\s*\(',
             'Use SourceAsset with the prepared export frame (no squeezing into the layout box).'),
    'L013': ('raw_text', r'(?<![\w.])(?:Text|RichText)\s*(?:\.rich\s*)?\(',
             'Use SourceText / SourceText.rich so line height, leading and ambient styles are fixed.'),
}
ARROW_OR_SYMBOL = re.compile(
    '^[\\s←-⇿⌀-⏿■-➿⬀-⯿〈-】'
    '›‹»«＞＜><\U0001f000-\U0001faff️]+$')
SUPPRESS = re.compile(r'lanhu-lint:\s*allow\s+(L\d{3})\b\s*(.*)')
GENERATED_HEADER = '// GENERATED by lanhu-design-fidelity/scripts/generate_flutter.py'


def scan(text: str):
    """Split Dart source into code (strings/comments blanked), strings and comments."""
    code, strings, comments = [], [], []
    i, n = 0, len(text)
    while i < n:
        ch = text[i]
        if text.startswith('//', i):
            end = text.find('\n', i)
            end = n if end < 0 else end
            comments.append((i, text[i:end]))
            code.append(' ' * (end - i))
            i = end
            continue
        if text.startswith('/*', i):
            end = text.find('*/', i + 2)
            end = n if end < 0 else end + 2
            comments.append((i, text[i:end]))
            code.append(re.sub(r'[^\n]', ' ', text[i:end]))
            i = end
            continue
        if ch in ('"', "'"):
            raw = i > 0 and text[i - 1] == 'r'
            quote = text[i:i + 3] if text[i:i + 3] in ("'''", '"""') else ch
            j = i + len(quote)
            while j < n and not text.startswith(quote, j):
                if text[j] == '\\' and not raw:
                    j += 2
                    continue
                if not raw and text.startswith('${', j):
                    depth, j = 1, j + 2
                    while j < n and depth:
                        depth += {'{': 1, '}': -1}.get(text[j], 0)
                        j += 1
                    continue
                if quote == ch and text[j] == '\n':
                    break
                j += 1
            end = min(n, j + len(quote))
            strings.append((i, text[i + len(quote):j]))
            code.append(quote + re.sub(r'[^\n]', ' ', text[i + len(quote):j]) + quote)
            i = end
            continue
        code.append(ch)
        i += 1
    return ''.join(code), strings, comments


def _line(text: str, offset: int) -> int:
    return text.count('\n', 0, offset) + 1


def _suppressions(text: str, comments):
    allowed = {}
    for offset, body in comments:
        match = SUPPRESS.search(body)
        if match:
            line = _line(text, offset)
            for target in (line, line + 1):
                allowed.setdefault(target, {})[match.group(1)] = match.group(2).strip()
    return allowed


def lint_text(text: str, rel: str):
    findings, suppressed = [], []
    code, strings, comments = scan(text)
    allowed = _suppressions(text, comments)

    def report(rule, offset, symbol):
        line = _line(text, offset)
        reason = allowed.get(line, {}).get(rule)
        entry = {'rule': rule, 'name': RULES.get(rule, ('glyph_icon',))[0], 'file': rel,
                 'line': line, 'symbol': symbol}
        if reason is not None:
            if reason:
                suppressed.append({**entry, 'reason': reason})
                return
            entry['message'] = 'Suppression needs a reason after the rule id.'
        else:
            entry['message'] = (RULES[rule][2] if rule in RULES else
                                'Arrow/emoji glyph used as an icon. Use the source asset or a '
                                'complete source path; missing assets use SourcePlaceholder.')
        findings.append(entry)

    for rule, (_, pattern, _) in RULES.items():
        for match in re.finditer(pattern, code):
            report(rule, match.start(), match.group(0).strip())
    for offset, value in strings:
        if value and ARROW_OR_SYMBOL.match(value):
            report('L002', offset, value)
    return findings, suppressed


def check_generated(path: Path, rel: str):
    """A generated file must match the bytes its codegen report recorded."""
    text = path.read_text(errors='replace')
    if not text.startswith(GENERATED_HEADER):
        return None
    report_path = path.with_suffix('').with_suffix('.codegen.json')
    if not report_path.exists():
        return {'rule': 'L011', 'name': 'generated_without_report', 'file': rel, 'line': 1,
                'message': f'Missing {report_path.name}; regenerate instead of editing by hand.'}
    expected = json.loads(report_path.read_text()).get('output_sha256')
    actual = hashlib.sha256(path.read_bytes()).hexdigest()
    if expected != actual:
        return {'rule': 'L011', 'name': 'generated_file_edited', 'file': rel, 'line': 1,
                'message': 'Generated file differs from its codegen report. Do not hand-edit; '
                           'use overrides/onTap in page code or regenerate.'}
    return {'ok': True}


def lint(paths, root: Path):
    findings, suppressed, checked, generated = [], [], [], []
    for path in paths:
        try:
            rel = str(path.resolve().relative_to(root.resolve()))
        except ValueError:
            rel = str(path.resolve())
        if '/lanhu_fidelity/' in f'/{rel}' or path.name.endswith('_test.dart') \
                or '/test/' in f'/{rel}':
            continue  # The primitives package and tests may use raw Flutter APIs.
        checked.append(rel)
        integrity = check_generated(path, rel)
        if integrity is not None:
            generated.append(rel)
            if not integrity.get('ok'):
                findings.append(integrity)
            continue
        text = path.read_text(errors='replace')
        found, allowed = lint_text(text, rel)
        findings.extend(found)
        suppressed.extend(allowed)
    return {'status': 'PASS' if not findings else 'FAIL', 'findings': findings,
            'suppressed': suppressed, 'checked_files': checked, 'generated_files': generated}


def dart_inputs(contract: dict, base: Path):
    return [(base / p).resolve() for p in contract.get('implementation_inputs', [])
            if str(p).endswith('.dart')]


def lint_contract(contract_path: Path):
    contract = json.loads(contract_path.read_text())
    if contract.get('dart_lint') in (None, 'off'):
        return {'status': 'SKIPPED', 'reason': 'legacy contract without dart_lint profile'
                if contract.get('dart_lint') is None else contract.get('dart_lint_reason', 'off'),
                'findings': [], 'suppressed': []}
    base = contract_path.resolve().parent
    paths = dart_inputs(contract, base)
    root = Path(os.path.commonpath([str(base), *(str(p) for p in paths)])) if paths else base
    return lint(paths, root)


def expand(sources):
    files = []
    for source in sources:
        if source.is_dir():
            files.extend(sorted(p for p in source.rglob('*.dart') if '.dart_tool' not in p.parts))
        else:
            files.append(source)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--contract', type=Path)
    parser.add_argument('--source', type=Path, action='append', default=[],
                        help='Dart file or directory (repeatable)')
    parser.add_argument('--root', type=Path, default=Path.cwd())
    parser.add_argument('--output', type=Path)
    args = parser.parse_args()
    if bool(args.contract) == bool(args.source):
        parser.error('use exactly one of --contract or --source')
    result = (lint_contract(args.contract) if args.contract
              else lint(expand(args.source), args.root))
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
    for item in result['findings'][:40]:
        print(f"{item['file']}:{item['line']}: {item['rule']} {item.get('symbol', '')} - {item['message']}")
    print(json.dumps({k: (len(v) if isinstance(v, list) else v) for k, v in result.items()},
                     ensure_ascii=False))
    return 0 if result['status'] in ('PASS', 'SKIPPED') else 2


if __name__ == '__main__':
    raise SystemExit(main())

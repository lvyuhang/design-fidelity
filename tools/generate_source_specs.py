"""Compile exact source primitives into Dart; no semantic inference or screenshot tracing."""
from pathlib import Path
import json, re
ROOT=Path(__file__).resolve().parents[1]
result={}
for category in ['modal','nav','appeal','feed','gender_none','gender_female','comments']:
 data=json.loads((ROOT/f'design_evidence/{category}-source.json').read_text())
 nodes={}
 lookup={n['node_id']:n for n in data.get('ancestors',[])+data['nodes']}
 for n in data['nodes']:
  r=n['raw_style']; b=n['bounds']
  if n['node_type'] not in ['shape','text']: continue
  item={'frame':[b[k] for k in ['x','y','width','height']], 'sourceId':n['node_id']}
  if n['text'] is not None:
   f=r['font']; run=n['text_spec']['text_runs'][0]
   item.update(text=n['text'],fontSize=f['size'],lineHeight=f['line'],weight=run['font_weight'],color=f['color'],align=f.get('textAlignment',0))
   if len(n['text_spec']['text_runs']) > 1:
    item['runs'] = []
    for part in n['text_spec']['text_runs']:
     values = [float(v) for v in re.findall(r'[\d.]+', part['color'])]
     item['runs'].append({'text':part['text'],'color':dict(zip(['r','g','b','a'],values))})
  else:
   item.update({k:r[k] for k in ['points','fills','borders','radius','shadow','opacity','isClosed','borderOptions'] if k in r})
  parent = lookup.get(n.get('parent_id'))
  flip_x = bool(r.get('isFlippedHorizontal'))
  flip_y = bool(r.get('isFlippedVertical'))
  while parent:
   pr = parent.get('raw_style', {})
   pb = parent.get('bounds')
   if pr.get('isFlippedHorizontal') and pb:
    item['frame'][0] = 2*pb['x']+pb['width']-item['frame'][0]-item['frame'][2]
    flip_x = not flip_x
   if pr.get('isFlippedVertical') and pb:
    item['frame'][1] = 2*pb['y']+pb['height']-item['frame'][1]-item['frame'][3]
    flip_y = not flip_y
   parent = lookup.get(parent.get('parent_id'))
  if flip_x: item['flipX'] = True
  if flip_y: item['flipY'] = True
  nodes[n['node_id']]=item
 result[category]=nodes
# JSON literal syntax is compatible with a const Dart map, with no null data in selected values.
text='// Generated by tools/generate_source_specs.py from immutable source evidence.\n// Values retain source-canvas coordinates and source node IDs.\nconst sourceSpecs = '+json.dumps(result,ensure_ascii=False,indent=2)+';\n'
(ROOT/'flutter_ui_components/lib/components/source_specs.g.dart').write_text(text)
